// Variabel => cara menyimpan sebuah data
/**
 * Pattern :
 * declaration name = value;
 */

// 1. DECLARATION
/**
 * -. let -> masih bisa berubah
 * -. const -> tidak bisa berubah
 * -. var (lupakan)
 */

// 2. NAME
// -> Menggunakan aturan casing camelCase pada variabel javascript
// Contoh : sudahMakan, apakahBenar, isTrue, isFacingRight, dll.

// 3. VALUE / DATA
/**
 * DATA TYPE :
 * 1. Primitive :
 *  -. string -> teks atau character
 *  -. number -> angka (bil. bulat / bil. desimal)
 *  -. boolean -> logika (true / false)
 *  -. undefined -> belum didefinisikan
 *  -. null -> kosong
 *  -. bigInt -> angka integer besar (banyak)
 *  -. symbol -> simbol
 *
 * 2. Reference (Object) :
 *  -. object
 *  -. array
 *  -. function
 *  -. class
 *  -. dll
 */

// CONTOH :
let nama = "Dicky"; //string
let umur = 20; // number (integer / bulat)
let tinggiBadan = 185.7; // number (float / desimal)
let sudahMakan = false; // boolean
